#!/usr/bin/env python3
"""
ctf.py — the only tool you need for this writeups repo.

Two commands:

  python ctf.py new <event-folder>/<challenge-folder>
        Create a new challenge writeup from the template, ready to fill in.
        Example:
          python ctf.py new 2026-cyberweek/web/my-new-chall

  python ctf.py            (or:  python ctf.py index)
        Rebuild every index/table automatically from the writeups.
        Run this after you add, rename, or edit any writeup.

Everything in the index tables is read from the little block at the top of
each challenge's README.md (the part between the --- lines). You never edit a
table by hand. If you don't want to run the script yourself, just tell Claude
"rebuild the CTF index" and it will run this for you.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
TEMPLATE = ROOT / "_templates" / "writeup.md"

# Nice headings for known folders; anything else uses the folder name as-is.
FOLDER_TITLES = {
    "heritage-trail": "🗺️ Heritage Trail",
    "blackstar": "🛰️ BLACKSTAR",
    "kivuli": "🕶️ Kivuli",
    "together": "🤝 Together",
    "blackout-protocol": "⚡ The Blackout Protocol",
    "lost-signal": "📻 The Lost Signal",
    "tidebreaker": "🌊 TIDEBREAKER",
    "gridlock": "🔌 GRIDLOCK",
    "invisible-courier": "📦 The Invisible Courier",
    "sc-series": "🔬 SC Series",
    "web": "🌐 Web",
    "forensics": "🧪 Forensics",
    "osint": "🕵️ OSINT",
    "crypto": "🔐 Crypto",
    "pwn": "💥 Pwn",
    "rev": "🔍 Reverse Engineering",
    "stego": "🖼️ Stego",
    "misc": "🎲 Misc",
}
# Preferred order of folders in the master index; unknown folders go last, A-Z.
FOLDER_ORDER = list(FOLDER_TITLES.keys())

START = "<!-- AUTO-INDEX:START -->"
END = "<!-- AUTO-INDEX:END -->"


def parse_frontmatter(readme: Path) -> dict:
    """Read the --- ... --- block at the top of a README into a dict."""
    text = readme.read_text(encoding="utf-8", errors="replace")
    m = re.match(r"^---\s*\n(.*?)\n---\s*\n", text, re.DOTALL)
    data = {}
    if not m:
        return data
    for line in m.group(1).splitlines():
        if ":" not in line:
            continue
        key, _, val = line.partition(":")
        val = val.strip().strip('"').strip("'")
        data[key.strip()] = val
    return data


def fmt_tags(raw: str) -> str:
    raw = (raw or "").strip().strip("[]")
    tags = [t.strip() for t in raw.split(",") if t.strip()]
    return ", ".join(f"`{t}`" for t in tags[:4])


def flag_cell(fm: dict) -> str:
    status = (fm.get("status") or "solved").lower()
    flag = fm.get("flag") or ""
    if status.startswith("unsolved") or flag.lower() in ("", "unsolved"):
        return "⛔ **unsolved**"
    return f"`{flag}`"


def challenge_row(folder_rel: str, link: str, fm: dict) -> str:
    name = fm.get("title") or link
    diff = (fm.get("difficulty") or "-").lower()
    return f"| [{name}]({link}) | {diff} | {fmt_tags(fm.get('tags',''))} | {flag_cell(fm)} |"


def table_header() -> str:
    return "| Challenge | Difficulty | Tags | Flag |\n|---|---|---|---|"


def write_between_markers(readme: Path, body: str, title_line: str):
    """Insert/replace the AUTO-INDEX block in a README, creating it if needed."""
    block = f"{START}\n{body}\n{END}"
    if readme.exists():
        text = readme.read_text(encoding="utf-8", errors="replace")
        if START in text and END in text:
            text = re.sub(re.escape(START) + r".*?" + re.escape(END), block, text, flags=re.DOTALL)
        else:
            text = text.rstrip() + "\n\n" + block + "\n"
    else:
        text = f"{title_line}\n\n{block}\n"
    readme.write_text(text, encoding="utf-8")


def folder_sort_key(name: str):
    return (FOLDER_ORDER.index(name) if name in FOLDER_ORDER else len(FOLDER_ORDER), name)


def rebuild_event(event_dir: Path):
    """Rebuild the event README plus each sub-folder README from challenge frontmatter."""
    groups = {}  # folder_name -> list[(link, fm)]
    for readme in sorted(event_dir.glob("*/*/README.md")):
        folder = readme.parent.parent.name          # e.g. "web"
        link = f"{folder}/{readme.parent.name}/"     # relative to event README
        groups.setdefault(folder, []).append((link, parse_frontmatter(readme)))

    if not groups:
        return 0

    total = sum(len(v) for v in groups.values())
    solved = sum(
        1 for v in groups.values() for _, fm in v
        if (fm.get("status") or "solved").lower().startswith("solved")
    )

    # --- master event index ---
    parts = [f"**{total} challenges — {solved} solved, {total - solved} unsolved.** "
             "Tables below are generated by `ctf.py`; don't edit them by hand.\n"]
    for folder in sorted(groups, key=folder_sort_key):
        rows = sorted(groups[folder], key=lambda x: x[0])
        parts.append(f"### {FOLDER_TITLES.get(folder, folder)}")
        parts.append(table_header())
        parts.extend(challenge_row(folder, link, fm) for link, fm in rows)
        parts.append("")
        # --- per-folder index ---
        freadme = event_dir / folder / "README.md"
        frows = [f"| [{fm.get('title', l)}]({Path(l).name}/) | {(fm.get('difficulty') or '-').lower()} "
                 f"| {fmt_tags(fm.get('tags',''))} | {flag_cell(fm)} |"
                 for l, fm in rows]
        fbody = table_header() + "\n" + "\n".join(frows)
        write_between_markers(freadme := freadme, fbody,
                              f"# {FOLDER_TITLES.get(folder, folder)}")
    write_between_markers(event_dir / "README.md", "\n".join(parts).rstrip(),
                          f"# {event_dir.name}")
    return total


def cmd_index():
    events = [d for d in ROOT.iterdir()
              if d.is_dir() and not d.name.startswith((".", "_")) and any(d.glob("*/*/README.md"))]
    grand = 0
    for ev in sorted(events):
        n = rebuild_event(ev)
        grand += n
        print(f"  {ev.name}: {n} challenges indexed")
    print(f"Done. {grand} challenges across {len(events)} event(s). Review & commit when ready.")


def cmd_new(rel: str):
    dest = ROOT / rel / "README.md"
    if dest.exists():
        sys.exit(f"Already exists: {dest}")
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(TEMPLATE.read_text(encoding="utf-8"), encoding="utf-8")
    print(f"Created {dest}\nFill it in, then run:  python ctf.py")


if __name__ == "__main__":
    args = sys.argv[1:]
    if args and args[0] == "new":
        if len(args) != 2:
            sys.exit("Usage: python ctf.py new <event-folder>/<challenge-folder>")
        cmd_new(args[1])
    elif not args or args[0] == "index":
        cmd_index()
    else:
        sys.exit(__doc__)
